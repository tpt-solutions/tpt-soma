/**
 * Escapes a value for use inside HTML text. Used for tooltip markup, where the
 * values come from uploaded data and must not be read as markup.
 */
export function escapeHtml(value: unknown): string {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
